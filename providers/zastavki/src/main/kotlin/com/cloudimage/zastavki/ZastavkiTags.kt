 * Matching is deliberately simple and total: normalize the query
 * (lowercase, whitespace to underscores), then score every slug —
 * exact, prefix, contains, query-starts-with-slug, and per-token
 * overlap in that order. No match is an honest miss: the caller
 * answers empty, never an error.
