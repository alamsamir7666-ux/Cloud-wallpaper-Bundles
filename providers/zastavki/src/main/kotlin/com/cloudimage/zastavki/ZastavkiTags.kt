    /**
     * A tag's display label: the parenthetical qualifier dropped,
     * underscores become spaces, each all-lowercase word capitalized —
     * `the_simpsons` -> "The Simpsons", `Hulk(comic_character)` ->
     * "Hulk". A word that already carries case (`3D`, `M.D.`) keeps it.
     */
    fun labelOf(slug: String): String =
        slug
            .substringBefore('(')
            .split('_')
            .filter { it.isNotBlank() }
            .joinToString(" ") { word ->
                if (word == word.lowercase()) {
                    word.replaceFirstChar { it.uppercase() }
                } else {
                    word
                }
            }.trim()

    /** The single best-scoring tag for a query — null on no match. */
    fun bestMatch(query: String): String? = scored(query).firstOrNull()?.slug

    /** The [count] best-scoring tags for a query, best first. */
    fun topMatches(
        query: String,
        count: Int,
    ): List<String> = scored(query).take(count).map { it.slug }

    /** One scored candidate; higher score wins, ties break alphabetically. */
    private data class Scored(
        val slug: String,
        val score: Int,
    )

    private fun scored(query: String): List<Scored> {
        val normalized = normalize(query)
        if (normalized.isEmpty()) return emptyList()
        val tokens = normalized.split('_').filter { it.isNotEmpty() }
        val hits = mutableListOf<Scored>()
        for (slug in slugs) {
            val target = slug.lowercase()
            val score =
                when {
                    target == normalized -> EXACT
                    target.startsWith(normalized) -> PREFIX
                    target.contains(normalized) -> CONTAINS
                    normalized.startsWith(target) && target.length >= MIN_WORD -> QUERY_HEAD
                    else -> tokenScore(tokens, target)
                }
            if (score > 0) hits += Scored(slug, score)
        }
        return hits.sortedWith(
            compareByDescending<Scored> { it.score }.thenBy { it.slug.lowercase() },
        )
    }

    /**
     * Multi-word queries against one-word-pair slugs: how many query
     * tokens the slug carries as whole words (or word-prefixes, the
     * autocompletion case). Partial credit, never a stretch match.
     */
    private fun tokenScore(
        tokens: List<String>,
        target: String,
    ): Int {
        if (tokens.isEmpty()) return 0
        val words = target.split('_').filter { it.isNotEmpty() }
        val matched =
            tokens.count { token ->
                words.any { word -> word == token || (token.length >= MIN_WORD && word.startsWith(token)) }
            }
        return if (matched == 0) 0 else TOKEN * matched / tokens.size
    }

    /** The query's own shape: trimmed, lowercased, whitespace folded. */
    private fun normalize(query: String): String = query.trim().lowercase().replace(WHITESPACE, "_")

    private const val EXACT = 100

    private const val PREFIX = 80

    private const val CONTAINS = 60

    private const val QUERY_HEAD = 55

    private const val TOKEN = 40

    private const val MIN_WORD = 3

    private val WHITESPACE = Regex("""\s+""")
}
